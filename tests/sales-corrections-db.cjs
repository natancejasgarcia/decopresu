    assert.equal((await one('select issue_sales_document($1) number', [invoice])).number, 'F/2026/0002');
    assert.equal((await one('select client_postal_code from sales_documents where id=$1', [invoice])).client_postal_code, '11002');
    const delivery = (await one("select create_sales_document('delivery_note',$1) id", [project])).id;
    await db.query('select save_sales_document($1,$2)', [delivery, full]);
    await db.query('select issue_sales_document($1)', [delivery]);
    const converted = (await one("select create_sales_document('invoice',null,$1) id", [delivery])).id;
    const convertedDoc = await one('select * from sales_documents where id=$1', [converted]);
    assert.equal(convertedDoc.client_city, full.client_city);
    assert.equal(convertedDoc.client_province, full.client_province);
    const correctionData = { ...full, correction_date: '2026-10-21', reason: 'Rectificacion de datos, sin cambio de importes.', lines: [{ unit_price: 99999 }] };
    const correction = (await one('select save_sales_data_correction($1,$2) id', [original, correctionData])).id;
    assert.equal((await one('select save_sales_data_correction($1,$2) id', [original, correctionData])).id, correction);
    const first = await one('select * from sales_data_corrections where id=$1', [correction]);
