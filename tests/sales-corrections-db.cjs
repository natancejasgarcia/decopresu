    const before = await one('select * from sales_documents where id=$1', [original]);
    for (let i = 0; i < 2; i++) {
      await db.exec(sql('migrations/20261021_sales_customer_address.sql'));
      await db.exec(sql('migrations/20261021_sales_data_corrections.sql'));
      await db.exec(sql('migrations/20261021_sales_trash.sql'));
    }
    assert.equal((await one('select legal_name from company_settings')).legal_name, 'DECORALIA ACABADOS, S.L.');
    assert.deepEqual((await one('select issuer from sales_documents where id=$1', [original])).issuer, before.issuer);
    const invoice = (await one("select create_sales_document('invoice',$1) id", [project])).id;
    await db.query('select save_sales_document($1,$2)', [invoice, data]);
    await assert.rejects(() => db.query('select issue_sales_document($1)', [invoice]), /codigo postal/);
    const full = { ...data, client_postal_code: '11002', client_city: 'Ciudad de prueba', client_province: 'Provincia de prueba' };
